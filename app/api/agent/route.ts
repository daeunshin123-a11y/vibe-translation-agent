// ─────────────────────────────────────────────────────────────
// 🔍 번역 리서치 에이전트
//
//   Plan  →  ReAct  →  Reflect  →  보고서
//
//   ① Plan     조사 계획을 스스로 세움                      💰 1건
//   ② ReAct    도구를 골라 쓰고, 결과를 보고 다음을 정함      💰 돌 때마다
//   ③ Reflect  "빠진 게 없나?" 스스로 점검                   💰 1건
//   ④ 보고서    후보 · 지역 · 중립 대안 · 추천
//
//   🔒 안전장치: 최대 단계 수와 도구 사용 횟수를 못박아 둡니다.
//      없으면 만족 못 한 에이전트가 무한정 돌아 무료 한도를 태웁니다.
// ─────────────────────────────────────────────────────────────

import { google } from "@ai-sdk/google";
import { generateText, streamText, stepCountIs } from "ai";
import { 도구만들기, 새기록, 한도 } from "@/lib/도구";
import { 지역목록, 올바른지역인가 } from "@/lib/지역";
import { 꺼내기, 담기 } from "@/lib/보관함";

export const runtime = "nodejs";
export const maxDuration = 120;

const 모델 = "gemini-3.6-flash";

// 🔒 안전장치
const 최대단계 = 8; // 생각→도구→생각 을 몇 번까지 돌지

export async function POST(요청: Request) {
  const 받은것 = await 요청.json();
  const 질문 = String(받은것.질문 ?? "").trim();
  const 목표지역 = String(받은것.지역 ?? "중립");
  const 다시조사 = 받은것.다시조사 === true; // 캐시 무시하고 새로 돌리기

  if (!질문) {
    return new Response("조사할 표현을 입력해 주세요.", { status: 400 });
  }
  const 지역 = 올바른지역인가(목표지역) ? 목표지역 : "중립";

  const 기록 = 새기록();
  const 도구 = 도구만들기(기록);

  // 화면에 한 줄씩 흘려보내기 위한 통로
  const 인코더 = new TextEncoder();
  const 흐름 = new ReadableStream({
    async start(내보내기) {
      const 보내기 = (종류: string, 내용: unknown) => {
        내보내기.enqueue(
          인코더.encode(JSON.stringify({ 종류, 내용 }) + "\n"),
        );
      };

      try {
        // ── ♻️ 0. 보관함 먼저 확인 (0원) ──────────────
        if (!다시조사) {
          const 보관된것 = await 꺼내기(질문, 지역);
          if (보관된것) {
            보내기("보관됨", 보관된것.저장시각);
            보내기("계획", 보관된것.계획);
            for (const 단계 of 보관된것.단계들) 보내기("도구", 단계);
            보내기("점검", 보관된것.점검);
            보내기("보고서", 보관된것.보고서);
            보내기("끝", {
              용어집검색: 0,
              웹검색: 0,
              단계수: 보관된것.단계들.length,
              캐시: true,
            });
            return; // 통로는 아래 finally 에서 한 번만 닫습니다
          }
        }

        // ── ① Plan ───────────────────────────────────
        보내기("상태", "계획을 세우는 중...");

        const 계획결과 = await generateText({
          model: google(모델),
          prompt: `너는 한국어↔스페인어 번역 조사원이다.
아래 표현을 조사할 계획을 3~5단계로 세워라.

조사 대상: "${질문}"
목표 지역: ${지역}

반드시 포함할 관점:
- 우리 팀 용어집에 이미 있는지
- 이 표현의 정확한 뜻과 뉘앙스
- 🌎 어느 나라/지역에서 주로 쓰는 표현인지
- 지역색이 강하면, ${지역 === "중립" ? "지역색 없는 중립 스페인어 대안" : `${지역}에서 자연스러운 표현`}

계획만 짧게 번호 목록으로 써라. 설명은 붙이지 마라.`,
        });

        보내기("계획", 계획결과.text.trim());

        // ── ② ReAct ──────────────────────────────────
        보내기("상태", "조사하는 중...");

        const 조사결과 = await generateText({
          model: google(모델),
          tools: 도구,
          stopWhen: stepCountIs(최대단계), // 🔒 여기서 멈춤
          prompt: `아래 계획에 따라 도구를 써서 조사하라.

조사 대상: "${질문}"
목표 지역: ${지역}

[계획]
${계획결과.text.trim()}

규칙:
- 반드시 먼저 용어집검색 도구를 써라.
- 웹검색은 최대 ${한도.웹검색}번만 쓸 수 있다. 질문을 구체적으로 만들어 아껴 써라.
- 🌎 지역 확인은 꼭 해라. "이 표현은 어느 나라에서 쓰는가?"
- 지역색이 강한 표현이면 ${지역 === "중립" ? "중립 대안" : `${지역}용 표현`}을 반드시 찾아라.
- 조사가 끝나면 알아낸 사실을 정리해서 말하라. (보고서는 나중에 쓴다)`,
        });

        for (const 단계 of 기록.단계) {
          보내기("도구", 단계);
        }
        보내기("조사요약", 조사결과.text.trim());

        // ── ③ Reflect ────────────────────────────────
        보내기("상태", "빠진 게 없는지 점검하는 중...");

        const 점검결과 = await generateText({
          model: google(모델),
          prompt: `아래 조사 결과를 점검하라.

조사 대상: "${질문}"
목표 지역: ${지역}

[조사 결과]
${조사결과.text.trim()}

다음을 확인하고, 부족한 점이 있으면 무엇이 부족한지 2~3줄로 지적하라.
충분하면 "충분함" 이라고만 답하라.

- 이 표현이 어느 지역에서 쓰이는지 확인했는가?
- ${지역 === "중립" ? "제시한 대안이 정말 중립적인가? 그것도 특정 나라 말은 아닌가?" : `제시한 표현이 ${지역}에서 자연스러운가?`}
- 근거가 있는가, 아니면 추측인가?`,
        });

        const 점검 = 점검결과.text.trim();
        보내기("점검", 점검);

        // ── ④ 보고서 ─────────────────────────────────
        보내기("상태", "보고서를 쓰는 중...");

        const 보고서 = streamText({
          model: google(모델),
          prompt: `아래 자료로 번역 조사 보고서를 써라.

조사 대상: "${질문}"
목표 지역: ${지역}

[조사 결과]
${조사결과.text.trim()}

[점검 의견]
${점검}

다음 형식으로, 한국어로, 간결하게 써라:

**뜻·뉘앙스**
(2~3줄)

**🌎 지역**
(어느 나라에서 쓰는 표현인지. 중립이면 "전 지역 통용"이라고 쓸 것)

**후보**
1. 표현 — 지역 — 어떤 상황에 어울리는지
2. ...

**✅ 추천**
(하나 고르고, 왜 그것인지 한 줄)

규칙:
- 용어집에서 찾은 내용은 올린 사람 별명을 밝혀라.
- 근거 없는 추측은 "추측입니다" 라고 밝혀라.
- 점검 의견에서 지적된 한계가 있으면 마지막에 짧게 덧붙여라.

⚠️ 그리고 맨 마지막 줄에, 용어집에 바로 등록할 수 있도록
아래 형식 그대로 한 줄을 덧붙여라. (설명 없이 이 줄만)

<<등록|추천번역|지역|한줄이유>>

- 추천번역: 위에서 고른 추천 표현 하나
- 지역: 중립 / 멕시코 / 스페인 / 아르헨티나 / 콜롬비아 중 하나
- 한줄이유: 60자 이내

예시: <<등록|¡No puede ser!|중립|멕시코 지역색 없이 전 지역에서 통함>>`,
        });

        let 보고서전체 = "";
        let 내보낸길이 = 0;
        for await (const 조각 of 보고서.textStream) {
          보고서전체 += 조각;
          // <<등록|...>> 부분은 화면에 안 보이게 걸러냅니다 (버튼용 자료라서)
          const 자른곳 = 보고서전체.indexOf("<<등록");
          const 보여줄것 = 자른곳 >= 0 ? 보고서전체.slice(0, 자른곳) : 보고서전체;
          if (보여줄것.length > 내보낸길이) {
            보내기("보고서", 보여줄것.slice(내보낸길이));
            내보낸길이 = 보여줄것.length;
          }
        }

        // 📌 등록용 값 뽑기
        const 등록줄 = 보고서전체.match(/<<등록\|([^|]*)\|([^|]*)\|([^>]*)>>/);
        const 등록감 = 등록줄
          ? {
              번역: 등록줄[1].trim().slice(0, 200),
              지역: 등록줄[2].trim(),
              이유: 등록줄[3].trim().slice(0, 300),
            }
          : null;
        if (등록감) 보내기("등록감", 등록감);

        // 보관할 때는 <<등록|...>> 을 뺀 깨끗한 보고서로 저장합니다
        보고서전체 = 보고서전체.replace(/<<등록\|[^>]*>>/, "").trim();

        // 💾 돈 주고 얻은 결과이니 반드시 저장합니다
        try {
          await 담기({
            단어: 질문,
            지역,
            계획: 계획결과.text.trim(),
            단계들: 기록.단계,
            점검,
            보고서: 보고서전체,
          });
          보내기("저장됨", true);
        } catch (저장오류) {
          console.error("[보관 실패]", 저장오류);
        }

        보내기("끝", {
          용어집검색: 기록.용어집검색,
          웹검색: 기록.웹검색,
          단계수: 기록.단계.length,
        });
      } catch (오류) {
        console.error("[에이전트 실패]", 오류);
        보내기(
          "오류",
          오류 instanceof Error ? 오류.message : "조사에 실패했습니다.",
        );
      } finally {
        내보내기.close();
      }
    },
  });

  return new Response(흐름, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "no-cache",
    },
  });
}

export const 지역선택지 = 지역목록;
